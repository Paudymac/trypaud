#!/usr/bin/env node
/**
 * Generates lib/image-imports/<name>.js — one module per page that renders
 * thumbnails, each a map of public image path -> static import, covering
 * only the images that page shows:
 *
 *   gallery.js    the `thumbnail` of every entry in data/gallery-items.json
 *   <page>.js     every image path in pages/<page>.js (a category page
 *                 using PortfolioGalleryTemplate), plus any data/*.json it
 *                 imports
 *
 * Why static imports: next/image treats them differently from a path
 * string. The file is copied to /_next/static/media with a content hash,
 * Vercel serves the optimized variants with a one-year immutable browser
 * cache (path-string images under public/ are always max-age=0, revalidate
 * on every visit), a replaced image can never be served stale, and Next
 * inlines a blur placeholder at build time.
 *
 * Why per page: an import carries its blur data, so one shared map for all
 * ~240 images cost every page ~36 KB of JS. Split, each page ships only
 * its own.
 *
 * Runs before `next build` and `next dev` (see package.json). Re-run it by
 * hand after adding images if the dev server is already up.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const outDir = path.join(root, 'lib', 'image-imports');
const RASTER = /\.(webp|jpe?g|png|gif|avif)$/i;
const PATH_RE = /["'`](\/images\/[^"'`\s]+)["'`]/g;
const JSON_IMPORT_RE = /from\s+["'][^"']*\/data\/([^"']+\.json)["']/g;

const exists = (p) => fs.existsSync(path.join(root, 'public', p));
const pathsIn = (text) =>
  [...text.matchAll(PATH_RE)].map((m) => m[1]).filter((p) => RASTER.test(p));

const targets = {};

// Gallery: thumbnails only — the lightbox loads the originals as-is
const items = JSON.parse(
  fs.readFileSync(path.join(root, 'data', 'gallery-items.json'), 'utf8')
);
targets.gallery = items.map((it) => it.thumbnail).filter((p) => RASTER.test(p));

// Category pages: inline paths plus any data JSON the page imports
for (const file of fs.readdirSync(path.join(root, 'pages'))) {
  if (!file.endsWith('.js')) continue;
  const text = fs.readFileSync(path.join(root, 'pages', file), 'utf8');
  if (!text.includes('PortfolioGalleryTemplate')) continue;
  let found = pathsIn(text);
  for (const m of text.matchAll(JSON_IMPORT_RE)) {
    found = found.concat(
      pathsIn(fs.readFileSync(path.join(root, 'data', m[1]), 'utf8'))
    );
  }
  if (found.length) targets[file.replace(/\.js$/, '')] = found;
}

fs.mkdirSync(outDir, { recursive: true });
let total = 0;
for (const [name, list] of Object.entries(targets)) {
  const sorted = [...new Set(list)].sort().filter((p) => {
    if (exists(p)) return true;
    console.warn(`gen-image-imports: ${name}: missing file for ${p}`);
    return false;
  });
  total += sorted.length;
  const lines = [
    '/* GENERATED by scripts/gen-image-imports.js — do not edit. */',
    '/* eslint-disable */',
    ...sorted.map((p, i) => `import i${i} from '@/public${p}';`),
    '',
    'const imageMap = {',
    ...sorted.map((p, i) => `  '${p}': i${i},`),
    '};',
    '',
    'export default imageMap;',
    '',
  ];
  fs.writeFileSync(path.join(outDir, `${name}.js`), lines.join('\n'));
  console.log(`gen-image-imports: ${name}: ${sorted.length} images`);
}
console.log(
  `gen-image-imports: ${total} imports across ${Object.keys(targets).length} modules`
);
