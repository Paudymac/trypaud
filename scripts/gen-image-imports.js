#!/usr/bin/env node
/**
 * Generates lib/image-imports.js: a static import for every raster image
 * path referenced by the gallery data and the pages, keyed by its public
 * path.
 *
 * Why: next/image treats a static import differently from a path string.
 * The file is copied to /_next/static/media with a content hash, Vercel
 * serves the optimized variants with a one-year immutable browser cache
 * (path-string images under public/ are always max-age=0, revalidate on
 * every visit), a replaced image can never be served stale, and Next
 * inlines a blur placeholder at build time.
 *
 * Runs before `next build` and `next dev` (see package.json). Re-run it by
 * hand after adding images if the dev server is already up.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'lib', 'image-imports.js');
const RASTER = /\.(webp|jpe?g|png|gif|avif)$/i;

const sources = [
  ...fs
    .readdirSync(path.join(root, 'data'))
    .filter((f) => f.endsWith('.json'))
    .map((f) => path.join(root, 'data', f)),
  ...fs
    .readdirSync(path.join(root, 'pages'))
    .filter((f) => f.endsWith('.js'))
    .map((f) => path.join(root, 'pages', f)),
];

const paths = new Set();
for (const file of sources) {
  const text = fs.readFileSync(file, 'utf8');
  for (const m of text.matchAll(/["'`](\/images\/[^"'`\s]+)["'`]/g)) {
    const p = m[1];
    if (!RASTER.test(p)) continue;
    if (!fs.existsSync(path.join(root, 'public', p))) {
      console.warn(`gen-image-imports: missing file for ${p}`);
      continue;
    }
    paths.add(p);
  }
}

const sorted = [...paths].sort();
const lines = [
  '/* GENERATED by scripts/gen-image-imports.js — do not edit. */',
  '/* eslint-disable */',
  ...sorted.map((p, i) => `import i${i} from '@/public${p}';`),
  '',
  'const imageImports = {',
  ...sorted.map((p, i) => `  '${p}': i${i},`),
  '};',
  '',
  'export default imageImports;',
  '',
];
fs.writeFileSync(out, lines.join('\n'));
console.log(
  `gen-image-imports: ${sorted.length} images -> lib/image-imports.js`
);
